"""SQLAlchemy Core `Table` objects mirroring the schema created by
`alembic/versions/0001_initial_schema.py`, column for column.

These are deliberately Core `Table`s, not a declarative ORM base — per the
note in `alembic/env.py`, the domain models are plain Pydantic and Alembic
migrations are written by hand rather than autogenerated from ORM classes.
This file exists purely so the application layer (`repository.py`) has a
typed way to build INSERT/SELECT statements, without hand-writing raw SQL
strings everywhere. If you add a column in a new migration, mirror it here
too — nothing enforces the two staying in sync automatically.
"""

from __future__ import annotations

from sqlalchemy import (
    CheckConstraint,
    Column,
    Date,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    MetaData,
    Table,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID

try:
    from pgvector.sqlalchemy import Vector
except ImportError:  # pragma: no cover - pgvector is a core dependency; this
    Vector = None  # keeps this module importable in contexts that don't need it

metadata = MetaData()

documents = Table(
    "documents",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("collection", Text, nullable=False),
    Column("title", Text, nullable=False),
    Column("tenant_id", Text, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False),
)

document_versions = Table(
    "document_versions",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("document_id", UUID(as_uuid=True), ForeignKey("documents.id", ondelete="CASCADE"), nullable=False),
    Column("label", Text, nullable=False),
    Column("effective_date", Date, nullable=True),
    Column("content_hash", Text, nullable=False, unique=True),
    Column("supersedes_id", UUID(as_uuid=True), ForeignKey("document_versions.id"), nullable=True),
    Column("blob_uri", Text, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
    # Added in migration 0002 — whole-document text + stats, 1:1 with the version.
    Column("full_text", Text, nullable=True),
    Column("char_count", Integer, nullable=True),
    Column("word_count", Integer, nullable=True),
    Column("token_count_estimate", Integer, nullable=True),
)

sections = Table(
    "sections",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("version_id", UUID(as_uuid=True), ForeignKey("document_versions.id", ondelete="CASCADE"), nullable=False),
    Column("parent_id", UUID(as_uuid=True), ForeignKey("sections.id"), nullable=True),
    Column("path", Text, nullable=False),
    Column("heading", Text, nullable=True),
    Column("number", Text, nullable=True),
    Column("page_start", Integer, nullable=True),
    Column("page_end", Integer, nullable=True),
    Column("ordinal", Integer, nullable=False),
)

images = Table(
    "images",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("version_id", UUID(as_uuid=True), ForeignKey("document_versions.id", ondelete="CASCADE"), nullable=False),
    Column("page_number", Integer, nullable=False),
    Column("bbox_x0", Float, nullable=False),
    Column("bbox_y0", Float, nullable=False),
    Column("bbox_x1", Float, nullable=False),
    Column("bbox_y1", Float, nullable=False),
    Column("uri", Text, nullable=False),
    Column("width", Integer, nullable=False),
    Column("height", Integer, nullable=False),
    Column("format", Text, nullable=False),
    Column("phash", Text, nullable=True),
    Column("caption", Text, nullable=True),
    Column("caption_model", Text, nullable=True),
    Column("captioned_at", DateTime(timezone=True), nullable=True),
)

tables = Table(
    "tables",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("version_id", UUID(as_uuid=True), ForeignKey("document_versions.id", ondelete="CASCADE"), nullable=False),
    Column("page_number", Integer, nullable=False),
    Column("bbox_x0", Float, nullable=False),
    Column("bbox_y0", Float, nullable=False),
    Column("bbox_x1", Float, nullable=False),
    Column("bbox_y1", Float, nullable=False),
    Column("uri", Text, nullable=False),
    Column("width", Integer, nullable=False),
    Column("height", Integer, nullable=False),
    Column("format", Text, nullable=False),
    Column("phash", Text, nullable=True),
)

_chunks_columns = [
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("version_id", UUID(as_uuid=True), ForeignKey("document_versions.id", ondelete="CASCADE"), nullable=False),
    Column("section_id", UUID(as_uuid=True), ForeignKey("sections.id"), nullable=True),
    Column("chunk_type", Text, nullable=False),
    Column("content", Text, nullable=False),
    Column("image_id", UUID(as_uuid=True), ForeignKey("images.id"), nullable=True),
    Column("embedding_model", Text, nullable=True),
    Column("page_start", Integer, nullable=True),
    Column("page_end", Integer, nullable=True),
    # `tsv` is a DB-generated column (see the migration) — never written to
    # from the application, so it's deliberately not listed as a Column here.
    CheckConstraint("chunk_type in ('text', 'image', 'table')", name="ck_chunks_chunk_type"),
]
if Vector is not None:
    # Inserted positionally to match the migration's column order; harmless
    # if it isn't (Core INSERTs are keyed by column name, not position).
    _chunks_columns.insert(6, Column("embedding", Vector(), nullable=True))

chunks = Table("chunks", metadata, *_chunks_columns)

# Added in migration 0004 — chat history and the harness's long-lived memory.
conversations = Table(
    "conversations",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("title", Text, nullable=False),
    Column("summary", Text, nullable=True),
    Column("summarized_upto", Integer, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("updated_at", DateTime(timezone=True), nullable=False),
)

messages = Table(
    "messages",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("conversation_id", UUID(as_uuid=True), ForeignKey("conversations.id", ondelete="CASCADE"), nullable=False),
    Column("ordinal", Integer, nullable=False),
    Column("role", Text, nullable=False),
    Column("content", Text, nullable=False),
    Column("citations", JSONB, nullable=False),
    Column("meta", JSONB, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
)

agent_memory = Table(
    "agent_memory",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("kind", Text, nullable=False),
    Column("version_id", UUID(as_uuid=True), ForeignKey("document_versions.id", ondelete="CASCADE"), nullable=True),
    Column("content", Text, nullable=False),
    Column("key", Text, nullable=False, unique=True),
    Column("source_conversation_id", UUID(as_uuid=True), ForeignKey("conversations.id", ondelete="SET NULL"), nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False),
)

agent_tables = Table(
    "agent_tables",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("workspace_id", Text, nullable=False),
    Column("title", Text, nullable=False),
    Column("description", Text, nullable=True),
    Column("columns", JSONB, nullable=False),
    Column("data", JSONB, nullable=False),
    Column("created_by", Text, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("updated_at", DateTime(timezone=True), nullable=False),
    CheckConstraint("created_by in ('agent', 'user')", name="ck_agent_tables_created_by"),
)

agent_table_revisions = Table(
    "agent_table_revisions",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("table_id", UUID(as_uuid=True), ForeignKey("agent_tables.id", ondelete="CASCADE"), nullable=False),
    Column("revision", Integer, nullable=False),
    Column("data", JSONB, nullable=False),
    Column("note", Text, nullable=True),
    Column("created_at", DateTime(timezone=True), nullable=False),
    UniqueConstraint("table_id", "revision", name="uq_agent_table_revisions_table_revision"),
)